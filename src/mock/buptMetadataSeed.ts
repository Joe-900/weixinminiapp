export function toBuptSeedBooks(addedBy: string): Book[] {
  const now = Date.now()
  return buptLibraryMetadataSeed.map((metadata, index) => {
    const bookId = `bupt_${index + 1}_${metadata.sourceRecordId ?? 'record'}`
    return {
      ...metadata,
      _id: bookId,
      bookId,
      author: metadata.author ?? '',
      isbn: metadata.isbn ?? '',
      cover: '',
      summary: '',
      status: 'online',
      addedBy,
      createdAt: now - index * 60000,
      updatedAt: now - index * 60000,
    }
  })
}
